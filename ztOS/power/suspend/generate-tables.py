#!/usr/bin/env python3
"""Copy the exact vendor sleep tables, rejecting unsupported operations."""
import argparse
import ast
import json
import operator
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ('third_party/vendor-kernel/drivers/soc/samsung/cal-if/'
                 'exynos9810/flexpmu_cal_system_exynos9810.h')
NAMES = [f'{phase}_{mode}' for mode in ('sleep', 'sleep_usbl2')
         for phase in ('enter', 'save', 'exit', 'earlywkup')]
SUPPORTED = {'PMUCAL_READ', 'PMUCAL_WRITE', 'PMUCAL_COND_READ',
             'PMUCAL_COND_WRITE', 'PMUCAL_SAVE_RESTORE',
             'PMUCAL_COND_SAVE_RESTORE', 'PMUCAL_WAIT'}


def generate(source):
    text = source.read_text()
    output = ['/* SPDX-License-Identifier: GPL-2.0-only */',
              '/* Generated by generate-tables.py from vendor Exynos9810 PMUCAL.',
              f' * Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()} */',
              '#define ZRN_SEQ(op, name, b, o, m, v, cb, co, cm, cv) \\\n    { op, name, b, o, m, v, cb, co, cm, cv, 0, false }']
    for name in NAMES:
        matches = re.findall(r'struct pmucal_seq ' + name +
                             r'\[\] = \{(.*?)\n\};', text, re.S)
        if len(matches) != 1:
            raise ValueError(f'{name}: expected exactly one source table')
        body = matches[0]
        operations = re.findall(r'PMUCAL_SEQ_DESC\((\w+)', body)
        if not operations or set(operations) - SUPPORTED:
            raise ValueError(f'{name}: missing or unsupported operations')
        output.append(f'static struct zrn_seq {name}[] = {{' +
                      body.replace('PMUCAL_SEQ_DESC(', 'ZRN_SEQ(') + '\n};')
    output.append('#undef ZRN_SEQ')
    return '\n\n'.join(output) + '\n'


def integer_expression(expression):
    """Evaluate only the integer operations used by the vendor table."""
    operations = {ast.LShift: operator.lshift, ast.RShift: operator.rshift,
                  ast.BitOr: operator.or_, ast.BitAnd: operator.and_,
                  ast.Add: operator.add, ast.Sub: operator.sub}

    def visit(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return node.value
        if isinstance(node, ast.BinOp) and type(node.op) in operations:
            return operations[type(node.op)](visit(node.left), visit(node.right))
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Invert):
            return ~visit(node.operand)
        raise ValueError(f'Unsupported vendor integer expression: {expression}')

    return visit(ast.parse(expression.strip(), mode='eval').body) & 0xffffffff


def generate_init_manifest(source):
    text = source.read_text()
    matches = re.findall(r'struct pmucal_seq pmucal_lpm_init\[\] = \{(.*?)\n\};', text, re.S)
    if len(matches) != 1:
        raise ValueError('expected one Linux PMUCAL initialization table')
    entries = []
    for line in matches[0].splitlines():
        if 'PMUCAL_SEQ_DESC' not in line:
            continue
        match = re.search(r'PMUCAL_SEQ_DESC\((\w+), "([^"]+)", (.*?)\),?$', line.strip())
        if not match or match[1] not in {'PMUCAL_WRITE', 'PMUCAL_WAIT'}:
            raise ValueError(f'unsupported initialization row: {line}')
        fields = [integer_expression(x) for x in match[3].split(',')]
        if len(fields) != 8:
            raise ValueError(f'invalid initialization row: {line}')
        entries.append(dict(operation=match[1], name=match[2], base=fields[0], offset=fields[1],
                            mask=fields[2], value=fields[3]))
    if not entries:
        raise ValueError('empty initialization table')
    return json.dumps(dict(source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                           table='pmucal_lpm_init', entries=entries), indent=2) + '\n'


def generate_init_header(source):
    manifest = json.loads(generate_init_manifest(source))
    core = {0x1a240000, 0x1a020000, 0x1d000000, 0x1d100000, 0x10020000}
    mif = {0x1b800000, 0x1b900000, 0x1ba00000, 0x1bb00000,
           0x1b810000, 0x1b910000, 0x1ba10000, 0x1bb10000}
    names = {'CPU_QCH_CLUSTER1_NONCPU_SYS_PWR_REG', 'TCXO_DURATION3',
             'EXT_REGULATOR_MIF_DURATION3', 'EXT_REGULATOR_DURATION3',
             'RESET_LPI_TIMEOUT', 'WDTRESET_LPI', 'AUD_CPU_OPTION'}
    selected = [e for e in manifest['entries'] if e['operation'] == 'PMUCAL_WRITE'
                and e['name'] not in {'CPUCL0_SHORTSTOP', 'CPUCL1_SHORTSTOP'}
                and (e['base'] in core | mif or e['name'].startswith('MEMORY_')
                     or e['name'] in names)]
    lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
             '/* Generated Samsung init subset: SRAM policy, core clocks, MIF clocks and delays.',
             ' * No GPU/media power-domain transitions or regulator-voltage writes.',
             ' * Source SHA256: ' + manifest['source_sha256'] + ' */',
             'struct zrn_init_setting { u32 base, offset, mask, value; const char *name; };',
             'static const struct zrn_init_setting init_settings[] = {']
    for e in selected:
        lines.append('    { 0x%08x, 0x%04x, 0x%08x, 0x%08x, "%s" },' %
                     (e['base'], e['offset'], e['mask'], e['value'], e['name']))
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    results = [('sleep-tables.h', generate(SOURCE)),
               ('init-prerequisites.json', generate_init_manifest(SOURCE)),
               ('init-memory.h', generate_init_header(SOURCE))]
    for name, result in results:
        target = Path(__file__).with_name(name)
        if args.check:
            if not target.exists() or target.read_text() != result:
                raise SystemExit(f'{name} differs from the vendor source')
        else:
            target.write_text(result)
